    @Transactional
    public int insertBom(Map<String, Object> payload) {
        String bomCode = required(payload, "bomCode", "BOM 编码");
        String productCode = required(payload, "productCode", "产品编码");
        String productName = required(payload, "productName", "产品名称");
        int updated = jdbc.update("insert into bom(tenant_id, bom_code, product_code, product_name, version, status, remark) values(?,?,?,?,?,?,?)",
                tenantId(), bomCode, productCode, productName,
                stringOr(payload.get("version"), "V1"), stringOr(payload.get("status"), "DRAFT"), string(payload.get("remark")));
        Long bomId = jdbc.queryForObject("select id from bom where tenant_id=? and bom_code=?", Long.class, tenantId(), bomCode);
        Object rawItems = payload.get("items");
        if (rawItems instanceof List<?> items) {
            for (Object rawItem : items) {
                if (!(rawItem instanceof Map<?, ?> item)) throw new IllegalArgumentException("BOM 物料明细格式不正确");
                Map<String, Object> normalized = new LinkedHashMap<>();
                item.forEach((key, value) -> normalized.put(String.valueOf(key), value));
                insertBomItemInternal(bomId, normalized);
            }
        }
        return updated;
    }

