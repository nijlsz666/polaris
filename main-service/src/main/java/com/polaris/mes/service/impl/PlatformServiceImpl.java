    /**
     * Creates a tenant and its first administrator in one transaction. The
     * payload intentionally contains no tenant id: the new id is generated by
     * the database and all subsequent requests are bound by the token.
     */
    @Transactional
    public Map<String, Object> registerTenant(Map<String, Object> payload, String passwordHash) {
        String tenantCode = required(payload, "tenantCode", "租户编码").toLowerCase(java.util.Locale.ROOT);
        String tenantName = required(payload, "tenantName", "企业名称");
        String username = required(payload, "username", "管理员用户名");
        String displayName = required(payload, "displayName", "管理员姓名");
        String contactName = stringOr(payload.get("contactName"), displayName);
        String contactEmail = string(payload.get("contactEmail"));
        if (!TENANT_CODE.matcher(tenantCode).matches()) {
            throw new IllegalArgumentException("租户编码需为 3-32 位小写字母、数字或短横线，且以字母开头");
        }
        if (username.length() < 3 || username.length() > 64) throw new IllegalArgumentException("管理员用户名长度必须为 3-64 位");
        if (passwordHash == null || passwordHash.isBlank()) throw new IllegalArgumentException("管理员密码不能为空");
        if (jdbc.queryForObject("select count(*) from sys_tenant where tenant_code=?", Integer.class, tenantCode) > 0) {
            throw new IllegalArgumentException("租户编码已被注册");
        }
        if (contactEmail != null && !contactEmail.isBlank() && !contactEmail.matches("^[^@\\s]+@[^@\\s]+\\.[^@\\s]+$")) {
            throw new IllegalArgumentException("联系邮箱格式不正确");
        }
        try {
            jdbc.update("insert into sys_tenant(tenant_code, tenant_name, plan_code, contact_name, contact_email, trial_ends_at, max_users, status) " +
                    "values(?,?,?,?,?,?,?,1)", tenantCode, tenantName, "STARTER", contactName, contactEmail,
                    Timestamp.from(Instant.now().plus(14, ChronoUnit.DAYS)), 10);
        } catch (org.springframework.dao.DuplicateKeyException ex) {
            throw new IllegalArgumentException("租户编码已被注册");
        }
        long newTenantId = jdbc.queryForObject("select id from sys_tenant where tenant_code=?", Long.class, tenantCode);
        seedTenantRoles(newTenantId);
        try {
            jdbc.update("insert into sys_user(tenant_id, username, display_name, password_hash, status, role_code) values(?,?,?,?,1,'admin')",
                    newTenantId, username, displayName, passwordHash);
        } catch (org.springframework.dao.DuplicateKeyException ex) {
            throw new IllegalArgumentException("管理员用户名已存在");
        }
        long userId = jdbc.queryForObject("select id from sys_user where tenant_id=? and username=?", Long.class, newTenantId, username);
        seedTenantPlatformAccess(newTenantId);
        Map<String, Object> result = new LinkedHashMap<>();
        result.put("tenantId", newTenantId);
        result.put("tenantCode", tenantCode);
        result.put("tenantName", tenantName);
        result.put("userId", userId);
        result.put("username", username);
        result.put("displayName", displayName);
        result.put("roleCode", "admin");
        return result;
    }

