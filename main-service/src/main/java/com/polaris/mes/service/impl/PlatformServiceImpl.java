    public int reportWork(Long id, Map<String, Object> payload) {
        int qty = number(payload.get("quantity"), 0);
        if (qty <= 0) throw new IllegalArgumentException("报工数量必须大于 0");
        Map<String, Object> workOrder = findWorkOrder(id);
        if (workOrder == null) throw new IllegalArgumentException("工单不存在或已删除");
        int planQty = number(workOrder.get("plan_qty"), 0);
        int completedQty = number(workOrder.get("completed_qty"), 0);
        if (completedQty + qty > planQty) throw new IllegalArgumentException("报工数量不能超过工单剩余数量");
        int updated = jdbc.update("update work_order set completed_qty=completed_qty+?, status=case when completed_qty+? >= plan_qty then 'COMPLETED' else 'IN_PROGRESS' end, updated_at=current_timestamp where tenant_id=? and id=? and deleted=0 and completed_qty+? <= plan_qty",
                qty, qty, tenantId(), id, qty);
        if (updated == 0) throw new IllegalArgumentException("工单不存在或已删除");
        return updated;
    }

