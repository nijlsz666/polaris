    @Transactional
    public int deleteRole(long id) {
        Map<String, Object> role = findRole(id);
        if ("admin".equals(role.get("role_code"))) throw new IllegalArgumentException("系统管理员角色不可删除");
        Number users = jdbc.queryForObject("select count(*) from sys_user where tenant_id=? and role_code=?", Number.class, tenantId(), role.get("role_code"));
        if (users != null && users.intValue() > 0) throw new IllegalArgumentException("该角色仍被用户使用，不能删除");
        jdbc.update("delete from sys_permission where tenant_id=? and role_code=?", tenantId(), role.get("role_code"));
        return jdbc.update("delete from sys_role where tenant_id=? and id=?", tenantId(), id);
    }

    @Transactional
    public List<Map<String, Object>> updateRolePermissions(String roleCode, List<Map<String, Object>> permissions) {
        if (one("select id from sys_role where tenant_id=? and role_code=?", tenantId(), roleCode) == null) throw new IllegalArgumentException("角色不存在");
        jdbc.update("delete from sys_permission where tenant_id=? and role_code=?", tenantId(), roleCode);
        if (permissions != null) for (Map<String, Object> permission : permissions) {
            String resourceType = stringOr(permission.get("resourceType"), "MENU");
            String resourceCode = required(permission, "resourceCode", "资源编码");
            String actionCode = stringOr(permission.get("actionCode"), "VIEW");
            jdbc.update("insert into sys_permission(tenant_id, role_code, resource_type, resource_code, action_code, field_mask_json, effect) values(?,?,?,?,?,?,?)",
                    tenantId(), roleCode, resourceType, resourceCode, actionCode, stringOr(permission.get("fieldMaskJson"), "{}"), stringOr(permission.get("effect"), "ALLOW"));
        }
        return listPermissions(roleCode);
    }

