    @Transactional
    public Map<String, Object> insertUser(Map<String, Object> payload, String passwordHash) {
        String username = required(payload, "username", "用户名");
        String displayName = required(payload, "displayName", "姓名");
        String roleCode = stringOr(payload.get("roleCode"), "operator");
        if (username.length() < 3 || username.length() > 64) throw new IllegalArgumentException("用户名长度必须为 3-64 位");
        if (passwordHash == null || passwordHash.isBlank()) throw new IllegalArgumentException("密码不能为空");
        if (jdbc.queryForObject("select count(*) from sys_role where tenant_id=? and role_code=? and status=1", Integer.class, tenantId(), roleCode) == 0) {
            throw new IllegalArgumentException("角色不存在或已停用");
        }
        try {
            jdbc.update("insert into sys_user(tenant_id, username, display_name, password_hash, status, role_code) values(?,?,?,?,?,?)",
                    tenantId(), username, displayName, passwordHash, number(payload.get("status"), 1), roleCode);
        } catch (org.springframework.dao.DuplicateKeyException ex) {
            throw new IllegalArgumentException("用户名已存在");
        }
        return findUserForAdmin(jdbc.queryForObject("select id from sys_user where tenant_id=? and username=?", Long.class, tenantId(), username));
    }

